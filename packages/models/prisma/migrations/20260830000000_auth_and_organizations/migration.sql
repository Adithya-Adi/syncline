-- AlterTable: Project joins an organization
--
-- Nullable first, so existing projects survive.
ALTER TABLE "Project" ADD COLUMN "organizationId" TEXT;

-- Existing projects predate multi-tenancy, so they are adopted by a single organization created
-- here. It deliberately has no members: the first person to sign up claims it during setup, which
-- avoids inventing a user row that no one can log in as.
INSERT INTO "organization" ("id", "name", "slug", "createdAt")
SELECT 'org_default', 'Default', 'default', NOW()
WHERE EXISTS (SELECT 1 FROM "Project" WHERE "organizationId" IS NULL);

UPDATE "Project" SET "organizationId" = 'org_default' WHERE "organizationId" IS NULL;

-- Now that every row has a value, the constraint can be enforced.
ALTER TABLE "Project" ALTER COLUMN "organizationId" SET NOT NULL;

